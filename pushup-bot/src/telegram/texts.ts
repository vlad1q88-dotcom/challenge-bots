import { MAX_ACTIVE_BOARDS, MAX_PARTICIPANTS, NICKNAME_MAX, NICKNAME_MIN } from '../constants.ts';

export const HELP = `<b>Бот-лидерборд челленджа по отжиманиям</b>

<b>Как это работает</b>
1. Инициатор бросает вызов: /new — задаёт название, срок и норму отжиманий в день.
2. Бот выдаёт код приглашения. Соперники принимают вызов: /join КОД (до ${MAX_PARTICIPANTS} человек вместе с инициатором).
3. Инициатор запускает отсчёт: /begin КОД.
4. Каждый день каждый шлёт в этот чат <b>скриншот недельного графика</b> из приложения — бот сам считывает число за сегодня, вводить руками ничего не нужно.
5. После каждого отчёта всем участникам прилетает обновлённый лидер-борд.

<b>Команды</b>
/new — бросить вызов (новый лидер-борд)
/join КОД — принять вызов
/begin КОД — запустить челлендж (только инициатор)
/board [КОД] — показать лидер-борд
/boards — мои челленджи
/nick КОД НИК — сменить ник (${NICKNAME_MIN}–${NICKNAME_MAX} символов)
/leave КОД — выйти до старта
/delete КОД — отменить челлендж до старта (только инициатор)
/badges — мои бейджи
/rules — правила и бейджи
/cancel — прервать текущий диалог`;

export const RULES = `<b>Правила</b>
• Максимум ${MAX_PARTICIPANTS} участников в одном челлендже, включая инициатора.
• Одновременно у тебя может быть максимум ${MAX_ACTIVE_BOARDS} лидер-борда: первый — оранжевый, второй — зелёный, третий — голубой.
• Норма отжиманий в день и срок задаются вручную при создании.
• Отчёт — скриншот вкладки <b>Week</b> из приложения. Бот распознаёт подпись над сегодняшним столбиком, ручной ввод числа не предусмотрен.
• Один и тот же скриншот дважды в челлендж не проходит, скриншот другой недели — тоже.
• <b>Не больше одного отчёта в день.</b> Второй отчёт за тот же день бот не примет — так не будет пропусков.
• Делать больше нормы можно, меньше — тоже, но в зачёт идёт общая сумма за весь челлендж.
• Столбик на борде — это 100% цели (норма × дни). Он заполняется по мере отчётов, ник стоит внутри столбика неподвижно.
• В конце бот считает, кто выполнил план, а кому сколько отжиманий не хватило. Перевыполнившие борются за звание чемпиона — побеждает наибольшая сумма.

<b>Бейджи</b>
${BADGES.map((badge) => `${badge.icon} <b>${badge.title}</b> — ${badge.description}`).join('\n')}

Серии считаются по дням, когда ты отчитался хотя бы в одном челлендже, и не сгорают при смене челленджа.`;
